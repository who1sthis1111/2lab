#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "ru-RU.UTF-8");

    // Массив 10х10 задан прямо в коде (карта высот)
    int matrix[10][10] = {
        {5, 8, 2, 7, 9, 1, 4, 3, 6, 0},
        {3, 1, 9, 4, 2, 8, 7, 6, 5, 2},
        {8, 4, 6, 1, 5, 3, 9, 2, 7, 4},
        {2, 7, 3, 9, 8, 6, 1, 5, 4, 3},
        {6, 9, 1, 5, 7, 4, 2, 8, 3, 1},
        {4, 2, 8, 3, 6, 0, 5, 9, 1, 7}, 
        {7, 5, 4, 8, 1, 9, 3, 2, 6, 8},
        {1, 6, 7, 2, 3, 5, 8, 4, 9, 5},
        {9, 3, 5, 6, 4, 7, 2, 1, 8, 3},
        {0, 8, 6, 3, 2, 1, 4, 7, 5, 9}
    };

    cout << "Найденные локальные минимумы:" << endl;

    // Проходим по каждой строке (i) и столбцу (j)
    for (int i = 0; i < 10; i++) {
        for (int j = 0; j < 10; j++) {
            
            bool is_min = true; // Предполагаем, что текущий элемент - минимум
            int current = matrix[i][j]; // Запоминаем текущее значение

            // Проверяем ВСЕХ соседей. 
            // Если сосед существует (не вышли за границу) и он МЕНЬШЕ или РАВЕН текущему,
            // значит текущий элемент - не локальный минимум.

            // 1. Сосед сверху (i-1, j)
            if (i > 0 && matrix[i-1][j] <= current) is_min = false;
            
            // 2. Сосед снизу (i+1, j)
            if (i < 9 && matrix[i+1][j] <= current) is_min = false;
            
            // 3. Сосед слева (i, j-1)
            if (j > 0 && matrix[i][j-1] <= current) is_min = false;
            
            // 4. Сосед справа (i, j+1)
            if (j < 9 && matrix[i][j+1] <= current) is_min = false;

            // Теперь проверяем диагонали:
            
            // 5. Сосед сверху-слева (i-1, j-1)
            if (i > 0 && j > 0 && matrix[i-1][j-1] <= current) is_min = false;
            
            // 6. Сосед сверху-справа (i-1, j+1)
            if (i > 0 && j < 9 && matrix[i-1][j+1] <= current) is_min = false;
            
            // 7. Сосед снизу-слева (i+1, j-1)
            if (i < 9 && j > 0 && matrix[i+1][j-1] <= current) is_min = false;
            
            // 8. Сосед снизу-справа (i+1, j+1)
            if (i < 9 && j < 9 && matrix[i+1][j+1] <= current) is_min = false;

            // Если флаг всё ещё true, значит мы проверили всех и никто не оказался меньше
            if (is_min) {
                cout << "Значение " << current << " в точке (" << i << ", " << j << ")" << endl;
            }
        }
    }

    return 0;
}